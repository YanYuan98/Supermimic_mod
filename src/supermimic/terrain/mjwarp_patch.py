"""Runtime fix of MuJoCo Warp's height-field narrowphase (docs/VISION_TERRAIN_PLAN.md §2.7, Phase C).

MuJoCo Warp collides a geom with a height field prism by prism (``collision_convex.ccd_hfield_kernel_builder``).
For capsules GJK first runs on the core segment (``collision_gjk.gjk_phase``): exact while the penetration is
below the radius. Deeper (penetration > 1 cm for the G1 foot capsules: landings, sprints) it falls back to EPA on
the full shapes, which for tilted capsules returns the reversed normal (0, 0, -1) for ~3 % of the prism contacts.
Such a contact pushes the foot *into* the field: running clips sank through flat height-field tiles that the same
policy crosses without failure on a box (capsule-box is an exact analytic test). A height field is solid below its
surface (with the thick bases of ``presets.MIN_TERRAIN_THICKNESS``), so no valid prism contact has a normal
pointing into the field: this patch drops those prism contacts; the other prisms under the capsule still support
it (each capsule overlaps several prisms and the kernel keeps up to 4 contacts per pair).

The patched builder is generated from the installed library's own source with one inserted check, located by an
anchor that must match exactly (``install_hfield_normal_filter`` raises otherwise, e.g. after a MuJoCo Warp
upgrade), written to a cache file (Warp compiles kernels from source files) and swapped in for
``collision_convex.ccd_hfield_kernel_builder``, which ``convex_narrowphase`` looks up at call time. Idempotent;
install it before a simulation is first stepped (mjlab captures CUDA graphs). Scenes without height fields are
unaffected. ``SUPERMIMIC_HFIELD_PATCH=0`` disables it in ``make_env`` (diagnostics).
"""

from __future__ import annotations

import hashlib
import importlib.util
import inspect
import os
from pathlib import Path

_ANCHOR = """          # skip prisms not in contact: ccd reports ncontact == 1 for separated geoms
          if ncontact == 0 or dist >= margin + gap:
            continue
"""
_INSERT = """
          # [supermimic] a height field is solid below its surface: drop a prism contact whose normal points into
          # the field (EPA failure once a capsule's core segment penetrates the prism)
          if wp.normalize(w1 - w2)[2] < -0.1:
            continue
"""
_HEADER = """# Generated by supermimic.terrain.mjwarp_patch from mujoco_warp._src.collision_convex (do not edit).
import warp as wp  # noqa: F401
from mujoco_warp._src import collision_convex as _cc

globals().update({k: v for k, v in vars(_cc).items() if not k.startswith("__")})


"""


_PATCHED_NAME = "ccd_hfield_kernel_builder_supermimic"


def _cache_dir() -> Path:
    return Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "supermimic" / "mjwarp_patch"


def patched_hfield_source() -> str:
    """Source of the patched ``ccd_hfield_kernel_builder`` module (raises if the library source changed)."""
    from mujoco_warp._src import collision_convex as cc

    fn = getattr(cc.ccd_hfield_kernel_builder, "_supermimic_original", cc.ccd_hfield_kernel_builder)
    src = inspect.getsource(inspect.unwrap(fn))
    if not src.lstrip().startswith("@cache_kernel"):
        src = "@cache_kernel\n" + src
    if src.count(_ANCHOR) != 1 or src.count("def ccd_hfield_kernel_builder(") != 1:
        raise RuntimeError("mujoco_warp ccd_hfield_kernel_builder changed: the height-field normal filter cannot be applied")
    # A distinct name: ``warp_util.cache_kernel`` keys its global kernel cache by function name + arguments, so under
    # the original name an already built unpatched kernel would be returned.
    src = src.replace("def ccd_hfield_kernel_builder(", f"def {_PATCHED_NAME}(")
    return _HEADER + src.replace(_ANCHOR, _ANCHOR + _INSERT)


def install_hfield_normal_filter() -> bool:
    """Swap in the patched height-field kernel builder; False if it was already installed."""
    from mujoco_warp._src import collision_convex as cc

    if getattr(cc.ccd_hfield_kernel_builder, "_supermimic_patched", False):
        return False
    original = cc.ccd_hfield_kernel_builder
    src = patched_hfield_source()
    digest = hashlib.sha1(src.encode()).hexdigest()[:16]
    path = _cache_dir() / f"hfield_{digest}.py"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(f".tmp{os.getpid()}")
        tmp.write_text(src)
        os.replace(tmp, path)  # atomic: concurrent ranks never import a partial file
    spec = importlib.util.spec_from_file_location(f"supermimic_mjwarp_hfield_{digest}", path)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    builder = getattr(mod, _PATCHED_NAME)
    builder._supermimic_patched = True
    builder._supermimic_original = original
    cc.ccd_hfield_kernel_builder = builder
    return True


def uninstall_hfield_normal_filter() -> None:
    """Restore MuJoCo Warp's own builder (tests / A-B diagnostics; kernels already captured keep their version)."""
    from mujoco_warp._src import collision_convex as cc

    original = getattr(cc.ccd_hfield_kernel_builder, "_supermimic_original", None)
    if original is not None:
        cc.ccd_hfield_kernel_builder = original
